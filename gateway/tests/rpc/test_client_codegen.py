from pathlib import Path

import pytest

from gateway.rpc.client_codegen import generate

_REPO_ROOT = Path(__file__).parents[3]
_CLIENT_SOURCE = (
    _REPO_ROOT / "generated" / "gateway_rpc_client" / "src" / "gateway_rpc_client"
)


def test_checked_in_client_matches_schema(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    monkeypatch.chdir(_REPO_ROOT / "gateway")

    changed = generate(
        _REPO_ROOT / "gateway" / "schema" / "gateway.openrpc.json",
        _CLIENT_SOURCE,
        check=True,
    )

    assert not changed


def test_every_client_module_is_marked_as_generated() -> None:
    for module in _CLIENT_SOURCE.rglob("*.py"):
        lines = module.read_text(encoding="utf-8").splitlines()
        assert lines[0].startswith("# Generated by "), module
        assert lines[1] == "# Do not edit this file manually.", module
        assert lines[2] == "", module
