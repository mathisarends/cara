from pathlib import Path

import pytest

from gateway_codegen import generate
from gateway_codegen.codegen import _namespace_class_names


def test_checked_in_client_matches_schema(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    package_root = Path(__file__).parents[3]
    monkeypatch.chdir(package_root / "gateway")

    changed = generate(
        package_root / "gateway" / "server" / "schema" / "gateway.openrpc.json",
        package_root / "gateway" / "client" / "src" / "gateway_client",
        check=True,
    )

    assert not changed


def test_every_client_module_is_marked_as_generated() -> None:
    package_root = Path(__file__).parents[3]
    client_source = package_root / "gateway" / "client" / "src" / "gateway_client"

    for module in client_source.rglob("*.py"):
        lines = module.read_text(encoding="utf-8").splitlines()
        assert lines[0].startswith("# Generated by "), module
        assert lines[1] == "# Do not edit this file manually.", module
        assert lines[2] == "", module


def test_namespace_classes_are_named_after_their_plural_domain() -> None:
    document = {
        "methods": [
            {"name": "automation.list"},
            {"name": "session.create"},
            {"name": "subscription.subscribe"},
            {"name": "turn.start"},
        ]
    }

    assert _namespace_class_names(document) == {
        "automation": "Automations",
        "session": "Sessions",
        "subscription": "Subscriptions",
        "turn": "Turns",
    }


def test_namespace_classes_pluralise_irregular_endings() -> None:
    document = {
        "methods": [
            {"name": "identity.get"},
            {"name": "status.get"},
            {"name": "batch.run"},
            {"name": "api_key.create"},
        ]
    }

    assert _namespace_class_names(document) == {
        "identity": "Identities",
        "status": "Statuses",
        "batch": "Batches",
        "api_key": "ApiKeys",
    }
