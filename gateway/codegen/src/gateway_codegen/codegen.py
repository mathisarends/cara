import argparse
import ast
import json
import re
import subprocess
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from jinja2 import Environment, PackageLoader
from pyrpckit.codegen import render_python_client
from pyrpckit.codegen.python import PythonClientOptions
from pyrpckit.codegen.writer import write_files

_DEFAULT_OUTPUT = Path("gateway/client/src/gateway_client")
_TEMPLATES = Environment(
    loader=PackageLoader("gateway_codegen"),
    autoescape=False,
    keep_trailing_newline=True,
)


@dataclass(frozen=True, slots=True)
class _Import:
    module: str
    names: tuple[str, ...]


def generate(schema_path: Path, output_directory: Path, *, check: bool = False) -> bool:
    """Render the complete client package from an OpenRPC document."""
    document = json.loads(schema_path.read_text(encoding="utf-8"))
    options = PythonClientOptions(
        package="gateway_client",
        client_name="GatewayClient",
        namespace_class_names=_namespace_class_names(document),
        source=schema_path.name,
    )
    rendered = dict(render_python_client(document, options))
    rendered["__init__.py"] = _client_init(
        rendered["__init__.py"], source=schema_path.name
    )
    rendered["transport.py"] = _TEMPLATES.get_template("transport.py.jinja2").render()
    generated = {
        path: _ruff_format(path, _separate_generated_header(content))
        for path, content in rendered.items()
    }
    changed = write_files(output_directory, generated, check=check)
    return bool(changed)


def _namespace_class_names(document: dict[str, Any]) -> dict[str, str]:
    """Name namespace classes after their domain: 'automation.list' -> Automations."""
    namespaces = {
        method["name"].split(".")[0]
        for method in document.get("methods", ())
        if "." in method["name"]
    }
    return {namespace: _plural(_pascal_case(namespace)) for namespace in namespaces}


def _pascal_case(namespace: str) -> str:
    return "".join(part.capitalize() for part in re.split(r"[_\-]", namespace))


def _plural(name: str) -> str:
    if name.endswith("y") and not name.endswith(("ay", "ey", "oy", "uy")):
        return f"{name[:-1]}ies"
    if name.endswith(("s", "x", "z", "ch", "sh")):
        return f"{name}es"
    return f"{name}s"


def _client_init(content: str, *, source: str) -> str:
    module = ast.parse(content)
    generated_imports = tuple(
        _Import(node.module, tuple(alias.name for alias in node.names))
        for node in module.body
        if isinstance(node, ast.ImportFrom) and node.module is not None
    )
    generated_public_names = next(
        ast.literal_eval(node.value)
        for node in module.body
        if isinstance(node, ast.Assign)
        and any(
            isinstance(target, ast.Name) and target.id == "__all__"
            for target in node.targets
        )
    )
    public_names = sorted(
        {
            *generated_public_names,
            "RpcClientError",
            "RpcRemoteError",
            "RpcTransport",
            "RpcTransportError",
            "SessionEvent",
            "SessionEventNotification",
            "WebSocketTransport",
        }
    )
    return _TEMPLATES.get_template("client_init.py.jinja2").render(
        generated_imports=generated_imports,
        public_names=public_names,
        source=source,
    )


def _separate_generated_header(content: str) -> str:
    lines = content.splitlines()
    if (
        len(lines) >= 2
        and lines[0].startswith("# Generated by ")
        and lines[1] == "# Do not edit this file manually."
    ):
        while len(lines) > 2 and not lines[2]:
            lines.pop(2)
        lines.insert(2, "")
    return "\n".join(lines) + "\n"


def _ruff_format(filename: str, content: str) -> str:
    """Apply the repo's ruff import sorting and formatting to generated code."""
    sorted_content = subprocess.run(
        ["ruff", "check", "--fix-only", "--stdin-filename", filename, "-"],
        input=content,
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    return subprocess.run(
        ["ruff", "format", "--stdin-filename", filename, "-"],
        input=sorted_content,
        capture_output=True,
        text=True,
        check=True,
    ).stdout


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate the typed Gateway client")
    parser.add_argument("schema", type=Path)
    parser.add_argument("--output", type=Path, default=_DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    changed = generate(arguments.schema, arguments.output, check=arguments.check)
    if arguments.check and changed:
        parser.error("generated client is out of date")


if __name__ == "__main__":
    main()
