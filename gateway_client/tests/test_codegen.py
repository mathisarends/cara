def test_models_have_generated_header_and_shared_base(
    specification: dict[str, Any],
) -> None:
    source = render_models(specification)

    assert source.splitlines()[:3] == [
        "# This file is generated from the Cara Gateway OpenRPC specification.",
        "# Source: gateway/schema/gateway.openrpc.json",
        "# Do not edit this file manually; run cara-gateway-client-generate.",
    ]
    assert "class GatewayModel(BaseModel):" in source
    assert 'model_config = ConfigDict(extra="forbid")' in source
    assert "class ConversationDelta(GatewayModel):" in source


def test_models_generate_enums_and_put_discriminator_first(
    specification: dict[str, Any],
) -> None:
    source = render_models(specification)
    model = source.split("class ConversationDelta(GatewayModel):", 1)[1]

    assert "class EventType(StrEnum):" in source
    assert 'CONVERSATION_DELTA = "conversation.delta"' in source
    assert "class RpcMethod(StrEnum):" in source
    assert 'CONVERSATION_SEND = "conversation.send"' in source
    assert (
        "type: Literal[EventType.CONVERSATION_DELTA] = EventType.CONVERSATION_DELTA"
    ) in model
    assert model.index("    type:") < model.index("    event_id:")


