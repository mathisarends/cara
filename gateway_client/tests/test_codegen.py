def test_generate_writes_compilable_package_and_is_deterministic(
    tmp_path: Path,
    specification: dict[str, Any],
) -> None:
    schema_path = tmp_path / "gateway.openrpc.json"
    output_directory = tmp_path / "gateway_client"
    schema_path.write_text(json.dumps(specification), encoding="utf-8")

    assert generate(schema_path, output_directory)
    assert not generate(schema_path, output_directory)

    expected_files = {
        output_directory / "models.py",
        output_directory / "client.py",
        output_directory / "namespaces" / "__init__.py",
        output_directory / "namespaces" / "conversation.py",
    }
    assert expected_files == set(output_directory.rglob("*.py"))
    for path in expected_files:
        compile(path.read_text(encoding="utf-8"), str(path), "exec")


def test_check_detects_drift_without_overwriting_generated_file(
    tmp_path: Path,
    specification: dict[str, Any],
) -> None:
    schema_path = tmp_path / "gateway.openrpc.json"
    output_directory = tmp_path / "gateway_client"
    schema_path.write_text(json.dumps(specification), encoding="utf-8")
    generate(schema_path, output_directory)
    client_path = output_directory / "client.py"
    client_path.write_text("# stale\n", encoding="utf-8")

    assert generate(schema_path, output_directory, check=True)
    assert client_path.read_text(encoding="utf-8") == "# stale\n"
    assert generate(schema_path, output_directory)
    assert not generate(schema_path, output_directory, check=True)


def test_cli_generates_and_reports_drift(
    tmp_path: Path,
    specification: dict[str, Any],
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    schema_path = tmp_path / "gateway.openrpc.json"
    output_directory = tmp_path / "generated"
    schema_path.write_text(json.dumps(specification), encoding="utf-8")
    monkeypatch.setattr(
        sys,
        "argv",
        [
            "cara-gateway-client-generate",
            str(schema_path),
            "--output",
            str(output_directory),
        ],
    )

    main()

    (output_directory / "client.py").write_text("# stale\n", encoding="utf-8")
    monkeypatch.setattr(
        sys,
        "argv",
        [
            "cara-gateway-client-generate",
            str(schema_path),
            "--output",
            str(output_directory),
            "--check",
        ],
    )
    with pytest.raises(SystemExit, match="2"):
        main()


